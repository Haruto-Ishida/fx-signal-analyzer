GLOSSARY: dict[str, Term] = {t.name: t for t in _T}
GROUPS = list(dict.fromkeys(t.group for t in _T))
FORBIDDEN = ("必ず儲", "絶対に儲", "確実に儲", "確実に利益", "絶対に勝", "必ず勝", "損しない")


def search(q: str = "", group: str | None = None) -> list[Term]:
    q = q.strip().lower()
    out = []
    for t in _T:
        if group and t.group != group:
            continue
        if q and q not in " ".join([t.name, t.short, t.what, t.read, t.use, t.caution]).lower():
            continue
        out.append(t)
    return out
